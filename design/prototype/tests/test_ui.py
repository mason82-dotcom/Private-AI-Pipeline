from pathlib import Path
from playwright.sync_api import sync_playwright
p=Path(__file__).resolve().parents[1]
html=(p/'index.html').read_text().replace('<link rel="stylesheet" href="./styles.css">','<style>'+(p/'styles.css').read_text()+'</style>').replace('<script defer src="./app.js"></script>','').replace('</body>','<script>'+(p/'app.js').read_text()+'</script></body>')
(p/'screenshots').mkdir(exist_ok=True)
errs=[]; results=[]
def check(label,x):
    results.append((label,bool(x)))
    if not x: print('FAILED',label)
with sync_playwright() as pw:
 b=pw.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox'])
 page=b.new_page(viewport={'width':1440,'height':900},device_scale_factor=1)
 page.on('pageerror',lambda e:errs.append(str(e)))
 page.set_content(html)
 check('initial dashboard',page.locator('.kpi').count()==4)
 check('no desktop horizontal overflow',not page.evaluate('document.documentElement.scrollWidth > innerWidth'))
 page.screenshot(path=str(p/'screenshots/desktop.png'),full_page=True)
 page.get_by_role('button',name='Wissensbasis',exact=True).first.click()
 check('knowledge page',page.locator('#view h1').text_content()=='Wissensbasis')
 page.locator('#docSearch').fill('gateway')
 check('knowledge search',page.locator('.data-table tbody tr').count()==1)
 page.locator('#docSearch').fill('nonexistentfoobarbaz')
 check('knowledge empty',page.get_by_text('Keine passenden Einträge gefunden.').count()==1)
 page.locator('#docSearch').fill('')
 check('knowledge search recover',page.locator('.data-table tbody tr').count()==5)
 page.locator('#docScope').select_option(label='SkyHub-Next')
 check('project scope filter',page.locator('.data-table tbody tr').count()==1)
 page.get_by_role('button',name='Gedächtnis',exact=True).first.click()
 page.get_by_role('button',name='Erinnerung anlegen').click()
 page.locator('#memTitle').fill('Testnotiz')
 page.locator('#memText').fill('Ein rein lokaler UI-Test')
 page.get_by_role('button',name='Als Demo-Notiz einfügen').click()
 check('memory simulated creation',page.get_by_text('Testnotiz').count()==1)
 page.get_by_role('button',name='Agenten',exact=True).first.click()
 page.locator('[data-tool="memory_remember"]').click()
 check('permission dialog shown',page.locator('#modalTitle').text_content()=='Berechtigung simulieren')
 page.get_by_role('button',name='Abbrechen').click()
 check('tool still locked after cancel',page.locator('[data-tool="memory_remember"]').get_attribute('aria-checked')=='false')
 page.locator('[data-page=chat]').click()
 page.locator('#prompt').fill('Bitte Demo-Antwort.')
 page.get_by_role('button',name='Nachricht simulieren').click()
 check('chat demo response',page.get_by_text('Es wurde kein lokales Sprachmodell angesprochen',exact=False).count()==1)
 page.get_by_role('button',name='Einstellungen',exact=True).first.click()
 page.get_by_role('switch',name='Kompakte Darstellung').click()
 check('density toggle',page.locator('body.compact').count()==1)
 page.keyboard.press('Control+k')
 check('command palette shortcut',page.locator('#cmdSearch').count()==1)
 page.locator('#cmdSearch').fill('mod')
 check('command palette filters',page.locator('.cmd-item').count()==1)
 page.keyboard.press('Escape')
 check('dialog closes on Escape',page.locator('.modal').count()==0)
 mobile=b.new_page(viewport={'width':390,'height':844},device_scale_factor=1)
 mobile.on('pageerror',lambda e:errs.append('MOBILE '+str(e)))
 mobile.set_content(html)
 check('mobile dashboard no overflow',not mobile.evaluate('document.documentElement.scrollWidth > innerWidth'))
 mobile.screenshot(path=str(p/'screenshots/mobile.png'),full_page=True)
 mobile.locator('#mobileMenu').click()
 check('mobile menu opens',mobile.locator('#sidebar.open').count()==1)
 mobile.get_by_role('button',name='Wissensbasis',exact=True).first.click()
 check('mobile navigation',mobile.locator('#view h1').text_content()=='Wissensbasis')
 check('mobile menu closes',mobile.locator('#sidebar.open').count()==0)
 check('mobile knowledge no overflow',not mobile.evaluate('document.documentElement.scrollWidth > innerWidth'))
 b.close()
print('TESTS',len(results),'PASSED',sum(x for _,x in results),'FAILED',len(results)-sum(x for _,x in results),'JS_ERRORS',errs)
for label,r in results: print('OK' if r else 'FAIL',label)
assert not errs and all(x for _,x in results)
